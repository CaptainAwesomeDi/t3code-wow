#!/usr/bin/env node
// Writes addon/T3Code/UI/Palettes.lua from Omarchy's built-in themes.
//
//   node tools/omarchy-themes.mjs <themes dir> [out file]
//
// The themes dir is Omarchy's own (the package's `themes/` folder, such as
// $OMARCHY_PATH/themes), not ~/.config/omarchy/themes, which holds the user's extra
// themes. Each theme's colors.toml is read as omarchy-ui reads it (spec/tokens.md,
// "Palette"): lines `key = "#rrggbb"`, plus `mode`. Only the keys the window uses are
// kept, as the theme writes them; the fallbacks for missing keys (color0..color8, the
// derived textDim and textFaint) are worked out in UI/Theme.lua, so one place holds
// them and the smoke test covers them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// The keys UI/Theme.lua reads. dark_fg is the legacy name for dark_foreground.
export const KEYS = [
  'background', 'foreground', 'dark_foreground', 'dark_fg', 'muted', 'accent',
  'red', 'green', 'yellow', 'orange', 'blue',
  'color0', 'color1', 'color2', 'color3', 'color4', 'color7', 'color8',
];

export function parseColors(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const color = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*"(#[0-9A-Fa-f]{6})"/);
    if (color) out[color[1]] = color[2].toLowerCase();
    const mode = line.match(/^\s*mode\s*=\s*"(light|dark)"/);
    if (mode) out.mode = mode[1];
  }
  return out;
}

// "tokyo-night" -> "Tokyo Night", as `omarchy theme list` names them.
export function label(id) {
  return id.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

export function readThemes(dir) {
  const themes = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory() && !e.isSymbolicLink()) continue;
    const file = path.join(dir, e.name, 'colors.toml');
    if (!fs.existsSync(file)) {
      process.stderr.write(`skipped ${e.name}: no colors.toml\n`);
      continue;
    }
    const raw = parseColors(fs.readFileSync(file, 'utf8'));
    const theme = { id: e.name, label: label(e.name), mode: raw.mode === 'light' ? 'light' : 'dark' };
    for (const k of KEYS) if (raw[k]) theme[k] = raw[k];
    themes.push(theme);
  }
  // Tokyo Night first: it's the default. The rest by name.
  themes.sort((a, b) => (a.id === 'tokyo-night' ? -1 : b.id === 'tokyo-night' ? 1 : a.label.localeCompare(b.label)));
  return themes;
}

export function toLua(themes) {
  const lines = [
    '-- Omarchy\'s built-in themes, for the modern window. Generated by',
    '-- tools/omarchy-themes.mjs from each theme\'s colors.toml; run it again rather',
    '-- than editing this file. UI/Theme.lua fills in what a theme leaves out.',
    '',
    'local _, ns = ...',
    '',
    'ns.PALETTES = {',
  ];
  for (const t of themes) {
    const fields = [`id = "${t.id}"`, `label = "${t.label}"`, `mode = "${t.mode}"`];
    for (const k of KEYS) if (t[k]) fields.push(`${k} = "${t[k]}"`);
    lines.push(`\t{ ${fields.join(', ')} },`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = process.argv[2];
  if (!dir) {
    process.stderr.write('usage: node tools/omarchy-themes.mjs <omarchy themes dir> [out file]\n');
    process.exit(2);
  }
  const here = path.dirname(fileURLToPath(import.meta.url));
  const out = process.argv[3] || path.join(here, '..', 'addon', 'T3Code', 'UI', 'Palettes.lua');
  const themes = readThemes(dir);
  fs.writeFileSync(out, toLua(themes));
  process.stdout.write(`wrote ${out}: ${themes.length} themes\n`);
}
